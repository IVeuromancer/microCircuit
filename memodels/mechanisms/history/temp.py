my_list = [6,8]
gidStart = 5

for j in my_list:
    if j == 0 or j == 0+gidStart:
        print('0/5')
    if j == 1 or j == 1+gidStart:
        print('1/6')
    if j == 2 or j == 2+gidStart:
        print('2/7')
    if j == 3 or j == 3+gidStart:
        print('3/8')
    if j == 4 or j == 4+gidStart:
        print('4/9')